def image_only(source: pathlib.Path, target: pathlib.Path) -> None:
    document = fitz.open(source)
    pixmap = document[0].get_pixmap(dpi=150)
    image = pixmap.tobytes("jpeg")
    output = fitz.open()
    page = output.new_page(width=document[0].rect.width, height=document[0].rect.height)
    page.insert_image(page.rect, stream=image)
    output.save(target)
    output.close()


def blank_pdf(path: pathlib.Path) -> None:
    c = canvas.Canvas(str(path), pagesize=A4)
    c.setFillColor(HexColor("#E8E5DE"))
    c.rect(42, 300, 511, 420, fill=1, stroke=0)
    c.setFillColor(GREY)
    c.setFont("Helvetica", 8)
    c.drawString(42, 60, "Illegible scan — image only, no text layer")
    c.save()


