def container_check(base: str) -> str:
    letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    total = 0
    for index, char in enumerate(base):
        number = int(char) if char.isdigit() else letters.index(char) + 10
        if number >= 11:
            number += 1
        total += number * (2**index)
    digit = total % 11
    return "0" if digit == 10 else str(digit)


def valid_container(prefix: str) -> str:
    body = prefix[:10]
    return body + container_check(body)


@dataclass
class Item:
    description: str
    hsn: str
    qty: int
    uom: str
    unit_price: Decimal
    amount: Decimal
    gross: Decimal
    net: Decimal
    chinese: str | None = None


@dataclass
class Spec:
    ref: str
    supplier: str
    buyer: str
    currency: str
    incoterm: str
    invoice_no: str
    invoice_date: str
    bl_no: str
    bl_date: str
    items: list[Item]
    freight: Decimal = Decimal("0")
    insurance: Decimal = Decimal("0")
    discount: Decimal = Decimal("0")
    packages_invoice: int = 0
    packages_packing: int = 0
    packages_bl: int = 0
    gross_invoice: Decimal = Decimal("0")
    gross_packing: Decimal = Decimal("0")
    gross_bl: Decimal = Decimal("0")
    net_invoice: Decimal = Decimal("0")
    net_packing: Decimal = Decimal("0")
    containers: list[str] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)
    scan: list[str] = field(default_factory=list)

    @property
    def total(self) -> Decimal:
        return (
            sum((item.amount for item in self.items), Decimal("0"))
            + self.freight
            + self.insurance
            - self.discount
        )


def money(value: Decimal) -> str:
    return f"{value:,.2f}"


def header(c: canvas.Canvas, title: str, spec: Spec, subtitle: str) -> None:
    c.setFillColor(black)
    c.setFont("Helvetica-Bold", 17)
    c.drawString(42, 806, spec.supplier.upper())
    c.setFont("Helvetica", 7.5)
    c.setFillColor(GREY)
    c.drawString(42, 792, "Synthetic document for demonstration · not a real shipment")
    c.setFillColor(black)

    c.setFont("Helvetica-Bold", 12)
    c.drawString(42, 748, title)
    c.setFont("Helvetica", 8)
    c.setFillColor(GREY)
    c.drawString(42, 734, subtitle)

    c.setStrokeColor(RULE)
    c.setLineWidth(0.7)
    c.line(42, 724, 553, 724)
    c.setFillColor(black)


def label(c: canvas.Canvas, x: float, y: float, text: str) -> None:
    c.setFont("Helvetica", 9)
    c.drawString(x, y, text)


def table_header(c: canvas.Canvas, y: float, columns: list[tuple[float, str]]) -> None:
    c.setFont("Helvetica-Bold", 7.5)
    c.setFillColor(GREY)
    for x, text in columns:
        c.drawString(x, y, text.upper())
    c.setFillColor(black)
    c.setStrokeColor(RULE)
    c.line(42, y - 5, 553, y - 5)


def footer(c: canvas.Canvas, spec: Spec, kind: str) -> None:
    c.setFont("Helvetica", 7)
    c.setFillColor(GREY)
    c.drawString(42, 46, f"{kind} · {spec.ref} · page 1 of 1")
    c.drawRightString(553, 46, "Generated by Customs-AI seed — synthetic data")
    c.setFillColor(black)


def invoice_pdf(spec: Spec, path: pathlib.Path) -> None:
    c = canvas.Canvas(str(path), pagesize=A4)
    header(c, "COMMERCIAL INVOICE", spec, "Supplier's declaration of goods and value")

    y = 700
    for text in [
        f"Invoice No: {spec.invoice_no}",
        f"Invoice Date: {spec.invoice_date}",
        f"Currency: {spec.currency}",
        f"Incoterm: {spec.incoterm}",
        f"Supplier: {spec.supplier}",
        f"Buyer: {spec.buyer}",
        f"Items: {len(spec.items)}",
    ]:
        label(c, 42, y, text)
        y -= 15

    y -= 8
    table_header(
        c,
        y,
        [(42, "No"), (70, "Description"), (300, "HSN"), (365, "Qty"), (425, "UOM"),
         (465, "Unit price"), (525, "Amount")],
    )
    y -= 18
    for index, item in enumerate(spec.items, start=1):
        c.setFont("Helvetica", 8)
        c.drawString(42, y, str(index))
        if item.chinese:
            c.setFont("STSong-Light", 8)
            c.drawString(70, y, item.chinese)
            offset = pdfmetrics.stringWidth(item.chinese, "STSong-Light", 8) + 5
            c.setFont("Helvetica", 8)
            c.drawString(70 + offset, y, item.description)
        else:
            c.drawString(70, y, item.description)
        c.drawString(300, y, item.hsn)
        c.drawRightString(400, y, f"{item.qty:,}")
        c.drawString(425, y, item.uom)
        c.drawRightString(495, y, f"{item.unit_price:,.2f}")
        c.drawRightString(553, y, f"{item.amount:,.2f}")
        y -= 22

    y -= 6
    c.setStrokeColor(RULE)
    c.line(330, y, 553, y)
    y -= 16
    for text, value in [
        ("Freight", spec.freight),
        ("Insurance", spec.insurance),
        ("Discount", spec.discount),
        ("Invoice Total", spec.total),
        ("Gross Weight", spec.gross_invoice),
        ("Net Weight", spec.net_invoice),
    ]:
        c.setFont("Helvetica-Bold" if "Total" in text else "Helvetica", 8.5)
        c.drawString(360, y, text)
        c.drawRightString(553, y, f"{money(value)} KG" if "Weight" in text else money(value))
        y -= 14

    c.setFont("Helvetica", 8.5)
    c.drawString(42, y - 16, f"Packages: {spec.packages_invoice} CTN")
    footer(c, spec, "Commercial invoice")
    c.save()


