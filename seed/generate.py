def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    manifest: dict[str, dict[str, str]] = {}
    for spec in build_specs():
        folder = OUT / spec.ref
        folder.mkdir(exist_ok=True)
        files: dict[str, str] = {}
        if "INVOICE" not in spec.missing:
            path = folder / "invoice.pdf"
            invoice_pdf(spec, path)
            files["INVOICE"] = str(path)
        if "PACKING" not in spec.missing:
            path = folder / "packing.pdf"
            packing_pdf(spec, path)
            if "PACKING" in spec.scan:
                scanned = folder / "packing-scan.pdf"
                image_only(path, scanned)
                files["PACKING"] = str(scanned)
            else:
                files["PACKING"] = str(path)
        if "BL" not in spec.missing:
            path = folder / "bl.pdf"
            bl_pdf(spec, path)
            if "BL" in spec.scan:
                blank = folder / "bl-illegible.pdf"
                blank_pdf(blank)
                files["BL"] = str(blank)
            else:
                files["BL"] = str(path)
        manifest[spec.ref] = files

    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(f"Generated {sum(len(v) for v in manifest.values())} PDFs in {OUT}")


if __name__ == "__main__":
    main()
